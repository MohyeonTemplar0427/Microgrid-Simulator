def rates_on(day,plan="SC1"):
    if type(day) is not str or plan not in PLANS:
        raise ValueError("Rockland rate date must be exact ISO and plan SC1/SC2.")
    try:
        parsed=date.fromisoformat(day)
    except (TypeError,ValueError):
        raise ValueError("Rockland rate date must be exact ISO.") from None
    if parsed.isoformat()!=day or not any(s<=day<=e for s,e in COVERAGE):
        raise ValueError("Rockland complete component coverage is October2026 only; no2025 or prior transmission-price fallback.")
    res=plan=="SC1"
    def r(name):return COMPONENTS[name]["rates_including_sut"]
    sbc=r("SBC");rggi=r("RGGI")
    from decimal import Decimal
    for values in (sbc,rggi):
        assert sum(Decimal(v) for k,v in values.items() if k!="total")==Decimal(values["total"])
    linear={"sbc_"+k.lower():float(v) for k,v in sbc.items() if k!="total"}
    linear.update({"rggi_"+k.lower():float(v) for k,v in rggi.items() if k!="total"})
    linear.update(transmission_service=float(r("SC1_transmission")["base"] if res else r("SC2_transmission_reference")["energy_all_per_kwh"]),
        transmission_surcharge_bundled=float(r("SC1_transmission")["bundled_surcharge"] if res else r("SC2_transmission_surcharge")["bundled_surcharge"]),
        bgs_reconciliation=float(r("BGS_reconciliation")["all_kwh"]),
        conservation_incentive=float(r("CIP")["SC1_Group_A_per_kwh" if res else "SC2_secondary_Group_B_per_kwh"]),
        zero_emission_certificate=float(r("ZEC")["total"]))
    return dict(customer=float(r("SC1_non_TOD_base")["customer_per_month"] if res else r("SC2_secondary_customer")["nondemand_metered_per_month"]),
        minimum=float(r("SC1_minimum")["monthly_minimum"] if res else r("SC2_minimum_and_demand_rules")["nondemand_metered_monthly_minimum"]),
        distribution_energy=(float(r("SC1_non_TOD_base")["winter_all_per_kwh"]),)*2 if res else (float(r("SC2_secondary_nondemand_energy")["winter_all_per_kwh"]),)*2,
        distribution_adjustment=(float(r("SC1_non_TOD_distribution_adjustment")["winter_all_per_kwh"]),)*2 if res else (0.,0.),
        generation_energy=(float(r("BGS_generation")["SC1_winter" if res else "SC2_winter"]),)*2,
        linear_rates=linear,season="winter",component_versions=deepcopy(COMPONENTS),
        tax_basis="Applicable filed CBT/SUT included once; BGS administration embedded",quantity_basis="raw import kWh")
