def _day(value):
    try:
        result = date.fromisoformat(str(value))
    except (ValueError, TypeError) as exc:
        raise ValueError("AES rate dates must be exact ISO local dates.") from exc
    return result.isoformat()


def generation_on(service_day):
    day = _day(service_day)
    for row in GENERATION:
        if row["effective_start"] <= day < row["effective_end_exclusive"]:
            return deepcopy(row)
    raise ValueError("AES G10 service-rendered generation date is unverified.")


def transmission_on(bill_day):
    day = _day(bill_day)
    for row in TRANSMISSION:
        if row["effective_start"] <= day < row["effective_end_exclusive"]:
            return deepcopy(row)
    raise ValueError("AES T08 bills-rendered transmission date is unverified.")


def rates_on(service_day, plan, *, bill_date):
    day, bill = _day(service_day), _day(bill_date)
    if plan not in PLANS or day[:7] != bill[:7]:
        raise ValueError("AES rates require matching complete calendar service/bill months and D17/D19.")
    month = day[:7]
    regime = next((r for r in REGIMES if month in r["months"]), None)
    if regime is None:
        raise ValueError("AES complete verified component coverage is January-June2025, June-July2026 and September-November2026; all gaps, August refund and later months reject.")
    g, t = generation_on(day), transmission_on(bill)
    res = plan == "D17"
    result = deepcopy({**regime["common"], **regime[plan]})
    result.update(supply_energy=float(g["ordinary_d17_usd_per_kwh"] if res else g["ordinary_d19_usd_per_kwh"]),
        transmission_energy=float(t["d17_usd_per_kwh"] if res else t["d19_usd_per_kwh"]),
        transmission_demand=0. if res else float(t["d19_usd_per_kw_all_billing_demand"]),
        low_load_transmission=0. if res else float(t["d19_low_load_substitute_usd_per_kwh"]),
        supply_source_grade=g["source_status"],
        source_versions=deepcopy(regime["source_versions"][month])+[
            dict(sheet="G10", id=g["id"], date_basis=g["date_basis"], source_grade=g["source_status"], source_ids=g["source_ids"]),
            dict(sheet="T08", id=t["id"], date_basis=t["date_basis"], source_grade=t["source_status"], source_ids=t["source_ids"]),
            dict(sheet="D33", revision=4, effective="2018-10-01", statutory_measurement_days=True),
            dict(sheet="D43", one_time_effective="2026-08-01", later_scope="confirmed prior receipt only")])
    return result
