def _at(component, day):
    choices = [v for v in COMPONENTS[component] if v["effective"] <= day]
    if not choices:
        raise ValueError("JCP&L has no verified component at this service date: "+component)
    return choices[-1]


def _optional_price(component, field):
    if field in component["rates"]:
        return float(component["rates"][field])
    status = component.get("status", "").lower()
    if "reserved" in status or "not introduced" in status:
        return 0.  # Explicit absence/deletion, never a missing-price fallback.
    raise ValueError("JCP&L component lacks a filed price or explicit non-applicability.")


def rates_on(day, plan="RS"):
    key = day.isoformat() if type(day) is date else day
    try:
        if not isinstance(key, str) or date.fromisoformat(key).isoformat() != key:
            raise ValueError
    except (ValueError, TypeError) as exc:
        raise ValueError("Use an exact ISO JCP&L New Jersey service date.") from exc
    if plan not in PLANS or not any(a <= key <= b for a,b in COVERAGE):
        raise ValueError("JCP&L verified RS/GS component coverage is January2025-October2026 only; no backfill or future extrapolation.")
    v={name:_at(name,key) for name in COMPONENTS}
    res=plan == "RS"; summer=6 <= int(key[5:7]) <= 9
    season="summer" if summer else "winter"
    base=v["RS_base" if res else "GS_base"]["rates"]
    delivery=v["GS_energy"]["rates"] if not res else base
    distribution=(tuple(float(delivery[f"summer_{part}_600_kwh"]) for part in ("first","excess")) if summer
                  else (float(delivery["winter_all_kwh"]),)*2) if res else tuple(float(delivery[f"{season}_{part}_1000_kwh"]) for part in ("first","excess"))
    generation=v["BGS_energy"]["rates"]
    generation=(tuple(float(generation[f"RS_summer_{part}_per_kWh"]) for part in ("first600","above600")) if summer
                else (float(generation["RS_winter_all_per_kWh"]),)*2) if res else (float(generation[f"GS_{season}_all_per_kWh"]),)*2
    linear={"transmission_service":float(base["transmission_per_kwh"]),
        "transmission_enhancement":float(v["TEC"]["rates"]["per_kwh"]),
        "bgs_reconciliation":float(v["BGS_reconciliation"]["rates"]["per_kwh"]),
        "bgs_reliability_must_run":float(v["RMR"]["rates"]["per_kwh"]),
        "non_utility_generation":float(v["NGC"]["rates"]["secondary_per_kwh"]),
        **{"sbc_"+k.lower():float(x) for k,x in v["SBC"]["rates"].items() if k != "total"},
        **{"rggi_"+k.lower():float(x) for k,x in v["RRC"]["rates"].items() if k != "total"},
        "zero_emission_certificate":_optional_price(v["ZEC"],"per_kwh"),
        "infrastructure_reliability":float(v["INFRA"]["rates"][plan]),
        "lost_revenue_adjustment":float(v["LRAM"]["rates"][plan]),
        "covid_recovery":_optional_price(v["CRC"],"per_kwh")}
    relief=(-30. if "2025-07-01" <= key <= "2025-08-31" else
            10. if "2025-09-01" <= key <= "2026-02-28" else 0.) if res else 0.
    customer=float(base["customer_per_month"] if res else base["single_phase_customer_per_month"])
    return dict(customer=customer, distribution_energy=distribution, generation_energy=generation,
        block_kwh=600. if res else 1000., season=season, linear_rates=linear,
        residential_generation_capacity_deferral=relief,
        gs_demand_rate=0. if res else float(base[f"{season}_demand_excess_10_kw"]),
        gs_minimum_rate=0. if res else float(base["minimum_demand_excess_10_kw"]),
        infrastructure_program=v["INFRA"]["program"],
        zec_status=v["ZEC"]["status"], crc_status=v["CRC"]["status"],
        component_versions={name:dict(effective=value["effective"],source=value["source"],status=value.get("status","filed_component")) for name,value in v.items()},
        tec_components=deepcopy(v["TEC"]["components"]),
        tax_basis="Published ordinary CBT/SUT and BGS capacity/ancillary/related costs retained once; no added tax/admin percentage",
        effective_basis="PartII3.07 service-effective per-kWh rates; full unchanged cycle blocks and monthly charges")
