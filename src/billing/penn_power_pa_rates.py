def rates_on(day,plan="RS"):
    if type(day) is not str or plan not in PLANS:
        raise ValueError("Penn Power needs exact ISO rate dates and RS/GS-S.")
    try:
        parsed=date.fromisoformat(day)
    except (TypeError,ValueError):
        raise ValueError("Penn Power needs exact ISO rate dates.") from None
    if parsed.isoformat()!=day or not any(s<=day<=e for s,e in COVERAGE):
        raise ValueError("Penn Power verified coverage is2025,January–June2026 andOctober2026; July–September DSIC and other periods have no fallback.")
    def pick(name):
        found=[r for r in COMPONENTS if r["component"]==name and r["start"]<=day<=r["end_inclusive"]]
        if len(found)!=1:raise ValueError("Missing/ambiguous Penn Power component: "+name)
        return found[0]
    res=plan=="RS";base=pick("base_"+plan)
    names=["STAS","TCJA","USC","EEC","SMT","DSS","DSIC","LEDC"]
    versions={n:pick(n) for n in names};versions["base"]=base
    spv=pick("SPVRC_balance_in_DSS" if day>="2026-06-01" else "SPVRC")
    versions["SPVRC"]=spv
    ptc=next(r for r in SUPPLY if r["start"]<=day<=r["end_inclusive"]);versions["PTC"]=ptc
    refund=next(r for r in COMPONENTS if r["component"]=="Non_eligible_cost_refund")
    versions["refund"]=refund
    key="RS" if res else "GS_S"
    return dict(customer=float(base["rates"]["customer_usd_month"]),distribution_kwh=float(base["rates"]["distribution_usd_kwh"]),
        ptc_kwh=float(ptc[plan]),dss_kwh=float(versions["DSS"]["rates"][key+"_usd_kwh"]),
        eec_kwh=float(versions["EEC"]["rates"][key+"_usd_kwh"]),
        usc_kwh=float(versions["USC"]["rates"]["RS_usd_kwh"]) if res else 0.,
        ledc_kwh=float(versions["LEDC"]["rates"][key+"_usd_kwh"]),smart_meter=float(versions["SMT"]["rates"][key+"_usd_month"]),spvrc_kwh=float(spv["rates"][key+"_usd_kwh"]),
        stas_fraction=float(versions["STAS"]["rates"]["fraction"]),tcja_fraction=float(versions["TCJA"]["rates"]["fraction"]),
        dsic_fraction=float(versions["DSIC"]["rates"]["fraction"]),
        january_refund=float(refund["rates"][key+"_usd_bill"]) if day[:7]=="2025-01" else 0.,
        source_versions=deepcopy(versions),tax_basis="PTC/composite GRT and supply administration included once; ordinary current-charge PA sales tax separate")
