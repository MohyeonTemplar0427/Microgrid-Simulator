def rates_on(day, plan="RS", *, bill_date=None):
    try:
        day = date.fromisoformat(str(day)).isoformat()
    except ValueError as exc:
        raise ValueError("CEI rates require an exact ISO service date.") from exc
    if plan not in PLANS:
        raise ValueError("Select The Illuminating Company RS or measured GS secondary SSO.")
    if bill_date is not None and str(bill_date)[:7] != day[:7]:
        raise ValueError("CEI initial scope requires matching calendar service and bill-rendered months.")
    for row in VERSIONS:
        if row["start"] <= day <= row["end"]:
            return {**deepcopy(row[plan]), "esp": row["esp"],
                    "source_versions": deepcopy(row["source_versions"])}
    raise ValueError("The Illuminating Company complete verified components are unavailable for " + day
                     + "; missing tariff periods are not interpolated or filled with current rates.")
